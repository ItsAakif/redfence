"""Standalone HTML report (no template engine, no external assets)."""

from __future__ import annotations

import html
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:  # pragma: no cover
    from redfence.bench.runner import CampaignResult

_OUTCOME_CLASS = {
    "violation": "bad",
    "satisfied": "ok",
    "unsupported": "warn",
    "inconclusive": "warn",
}


def _metric_rows(result: CampaignResult) -> str:
    rows = []
    for name, value in result.metrics.model_dump().items():
        if name == "notes":
            continue
        if isinstance(value, dict):
            display = "n/a" if value["value"] is None else f"{value['value']:.3f}"
            ci = (
                ""
                if value["ci_low"] is None
                else f" [{value['ci_low']:.3f}, {value['ci_high']:.3f}]"
            )
            rows.append(
                f"<tr><td>{html.escape(name)}</td><td>{value['numerator']}/{value['denominator']}</td>"
                f"<td>{display}{ci}</td></tr>"
            )
    return "\n".join(rows)


def _evidence_rows(result: CampaignResult) -> str:
    rows = []
    for item in result.evidence:
        css = _OUTCOME_CLASS.get(item.outcome.value, "")
        rows.append(
            f"<tr class='{css}'><td>{html.escape(item.oracle_id)}</td>"
            f"<td>{html.escape(item.facet)}</td><td>{html.escape(item.outcome.value)}</td>"
            f"<td>{html.escape(item.expected)}</td><td>{html.escape(item.observed)}</td></tr>"
        )
    return "\n".join(rows)


def write_html_report(result: CampaignResult, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    violations = [item for item in result.evidence if item.is_violation]
    manifest = result.manifest
    page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>RedFence report - {html.escape(result.scenario_id)}</title>
<style>
body {{ font-family: system-ui, sans-serif; margin: 2rem; color: #1b1b1b; }}
h1 {{ font-size: 1.4rem; }}
table {{ border-collapse: collapse; width: 100%; margin: 1rem 0; font-size: 0.9rem; }}
th, td {{ border: 1px solid #ccc; padding: 0.4rem 0.6rem; text-align: left; vertical-align: top; }}
th {{ background: #f2f2f2; }}
tr.bad {{ background: #fde7e7; }} tr.ok {{ background: #eaf7ea; }}
tr.warn {{ background: #fff7e0; }}
.meta {{ font-size: 0.85rem; color: #555; }}
code {{ background: #f4f4f4; padding: 0 0.2rem; }}
</style></head><body>
<h1>RedFenceBench security report</h1>
<p class="meta">Scenario <code>{html.escape(result.scenario_id)}</code> &middot;
profile <strong>{html.escape(result.profile)}</strong> &middot;
exit code <strong>{result.exit_code}</strong> &middot;
dataset <code>{html.escape(str(manifest.get('dataset_version')))}</code> &middot;
seed <code>{html.escape(str(manifest.get('seed')))}</code></p>
<p><strong>{len(violations)}</strong> confirmed violation(s).</p>
<h2>Evidence</h2>
<table><thead><tr><th>Oracle</th><th>Facet</th><th>Outcome</th><th>Expected</th><th>Observed</th></tr></thead>
<tbody>{_evidence_rows(result)}</tbody></table>
<h2>Metrics</h2>
<table><thead><tr><th>Metric</th><th>n/d</th><th>Value [95% Wilson CI]</th></tr></thead>
<tbody>{_metric_rows(result)}</tbody></table>
<p class="meta">Generated by RedFence {html.escape(str(manifest.get('package_version')))}. This
report is research output, not a certification of compliance.</p>
</body></html>
"""
    path.write_text(page, encoding="utf-8")
    return path
